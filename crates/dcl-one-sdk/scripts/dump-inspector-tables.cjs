
const fs = require('fs')
const path = require('path')

const inspectorDir =
  process.argv[2] ||
  path.join(
    process.env.HOME,
    '.cache/dcl-one-sdk/inspector-host/node_modules/@dcl/inspector'
  )
const outDir = path.join(__dirname, '..', 'src/vendor/inspector-shim')

const insp = require(inspectorDir)
const inspectorVersion = require(path.join(inspectorDir, 'package.json')).version

const ECS = require(path.join(inspectorDir, '../ecs/dist-cjs'))

const probeEngine = ECS.Engine()
const factoryByName = new Map()
for (const factory of Object.values(ECS.components || {})) {
  if (typeof factory !== 'function') continue
  try {
    const def = factory(probeEngine)
    if (def && def.componentName) factoryByName.set(def.componentName, def)
  } catch {
  }
}

const { engine } = insp.createEngineContext()
const components = []
for (const c of engine.componentsIter()) {
  const factory = factoryByName.get(c.componentName)
  const sameAsFactory =
    !!factory &&
    JSON.stringify(factory.schema.jsonSchema) === JSON.stringify(c.schema.jsonSchema)
  components.push({
    name: c.componentName,
    id: c.componentId,
    type: c.componentType,
    defineFrom: sameAsFactory ? 'ecs' : 'schema',
    jsonSchema: c.schema.jsonSchema,
  })
}

const table =
  '{\n' +
  `  "$comment": ${JSON.stringify(
    'GENERATED by scripts/dump-inspector-tables.cjs — do not hand-edit. ' +
      'A version-pinned snapshot of every component @dcl/inspector defines.'
  )},\n` +
  `  "inspectorVersion": ${JSON.stringify(inspectorVersion)},\n` +
  '  "components": [\n' +
  components.map(c => '    ' + JSON.stringify(c)).join(',\n') +
  '\n  ]\n}\n'

fs.writeFileSync(path.join(outDir, 'component-schemas.json'), table)

const { engine: e2, components: c2 } = insp.createEngineContext()
c2.Nodes.create(e2.RootEntity, {
  value: [
    { entity: e2.RootEntity, children: [], open: true },
    { entity: e2.PlayerEntity, children: [] },
    { entity: e2.CameraEntity, children: [] },
  ],
})
c2.Scene.create(e2.RootEntity, {
  name: 'Test Scene',
  description: 'This is a test scene',
  thumbnail: 'assets/scene/thumbnail.png',
  ageRating: insp.SceneAgeRating.Adult,
  skyboxConfig: { fixedTime: 36000, transitionMode: 0  },
  categories: [],
  author: '',
  email: '',
  tags: [],
  layout: { base: { x: 0, y: 0 }, parcels: [{ x: 0, y: 0 }] },
})
const { Composite } = ECS
const minimal = Composite.toJson(insp.dumpEngineToComposite(e2, 'json'))

fs.writeFileSync(
  path.join(outDir, 'minimal-composite.json'),
  JSON.stringify(minimal, null, 2) + '\n'
)

const AP = require(path.join(inspectorDir, '../asset-packs'))
const assetPacksVersion = require(path.join(inspectorDir, '../asset-packs/package.json')).version
const { engine: e3 } = insp.createEngineContext()
const onRoot = (engine) => {
  const out = {}
  for (const c of engine.componentsIter()) {
    if (typeof c.getOrNull !== 'function') continue
    const v = c.getOrNull(engine.RootEntity)
    if (v !== null && v !== undefined) out[c.componentName] = v
  }
  return out
}
const before = Object.keys(onRoot(e3))
if (before.length) {
  throw new Error(`createEngineContext already seeds the root entity (${before.join(', ')}); teach this script about it`)
}
AP.initComponents(e3)
const rootComponents = onRoot(e3)

fs.writeFileSync(
  path.join(outDir, 'root-components.json'),
  JSON.stringify(
    {
      $comment:
        'GENERATED by scripts/dump-inspector-tables.cjs — do not hand-edit. ' +
        "What @dcl/asset-packs' initComponents puts on the root entity, applied " +
        'by host.js seedRootComponents after every composite load.',
      inspectorVersion,
      assetPacksVersion,
      components: rootComponents,
    },
    null,
    2
  ) + '\n'
)

console.log(`@dcl/inspector ${inspectorVersion} (+ @dcl/asset-packs ${assetPacksVersion})`)
console.log(`component-schemas.json: ${components.length} components`)
console.log(`minimal-composite.json: ${minimal.components.length} component groups`)
console.log(
  `root-components.json: ${Object.keys(rootComponents).join(', ')}` +
    ` (${rootComponents['asset-packs::ActionTypes']?.value.length ?? 0} action types)`
)
